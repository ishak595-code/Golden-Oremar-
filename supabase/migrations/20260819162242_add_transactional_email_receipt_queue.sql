create or replace function public.service_claim_transactional_email_jobs_v1(p_worker_id text,p_limit integer default 10)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare result jsonb;
begin
  if char_length(btrim(coalesce(p_worker_id,''))) not between 8 and 120 then raise exception 'invalid_worker_id' using errcode='22023'; end if;
  if p_limit not between 1 and 25 then raise exception 'invalid_claim_limit' using errcode='22023'; end if;
  with picked as (
    select j.id
    from private.transactional_email_jobs j
    where j.attempts<8 and j.available_at<=timezone('utc',now())
      and (j.status in ('pending','failed') or (j.status='processing' and j.locked_at<timezone('utc',now())-interval '15 minutes'))
    order by j.available_at,j.id
    for update skip locked
    limit p_limit
  ), claimed as (
    update private.transactional_email_jobs j
    set status='processing',attempts=j.attempts+1,locked_at=timezone('utc',now()),locked_by=btrim(p_worker_id),last_error=null
    where j.id in (select id from picked)
    returning j.id,j.kind,j.aggregate_id,j.payload,j.attempts
  )
  select coalesce(jsonb_agg(jsonb_build_object('id',id,'kind',kind,'aggregateId',aggregate_id,'payload',payload,'attempt',attempts) order by id),'[]'::jsonb)
  into result from claimed;
  return jsonb_build_object('ok',true,'jobs',result);
end;
$function$;

create or replace function public.service_complete_transactional_email_job_v1(p_job_id bigint,p_worker_id text,p_provider_message_id text)
returns boolean
language plpgsql
security definer
set search_path to ''
as $function$
begin
  update private.transactional_email_jobs
  set status='sent',provider_message_id=left(btrim(coalesce(p_provider_message_id,'')),240),sent_at=timezone('utc',now()),locked_at=null,locked_by=null,last_error=null
  where id=p_job_id and status='processing' and locked_by=btrim(coalesce(p_worker_id,''));
  return found;
end;
$function$;

create or replace function public.service_fail_transactional_email_job_v1(p_job_id bigint,p_worker_id text,p_error text,p_retryable boolean default true)
returns boolean
language plpgsql
security definer
set search_path to ''
as $function$
begin
  update private.transactional_email_jobs
  set status=case when coalesce(p_retryable,false) and attempts<8 then 'failed' else 'dead_letter' end,
      available_at=case
        when not coalesce(p_retryable,false) or attempts>=8 then available_at
        when attempts<=1 then timezone('utc',now())+interval '1 minute'
        when attempts=2 then timezone('utc',now())+interval '2 minutes'
        when attempts=3 then timezone('utc',now())+interval '5 minutes'
        when attempts=4 then timezone('utc',now())+interval '15 minutes'
        when attempts=5 then timezone('utc',now())+interval '30 minutes'
        when attempts=6 then timezone('utc',now())+interval '1 hour'
        else timezone('utc',now())+interval '6 hours'
      end,
      last_error=left(btrim(coalesce(p_error,'transactional_email_failed')),500),locked_at=null,locked_by=null
  where id=p_job_id and status='processing' and locked_by=btrim(coalesce(p_worker_id,''));
  return found;
end;
$function$;

create or replace function public.super_admin_list_transactional_email_jobs_v1(p_status text default null,p_limit integer default 50)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $function$
declare normalized text:=nullif(lower(btrim(coalesce(p_status,''))),'' ); result jsonb;
begin
  if auth.uid() is null or not coalesce(private.is_super_admin(),false) then raise exception 'super_admin_required' using errcode='42501'; end if;
  if normalized is not null and normalized not in ('pending','processing','failed','sent','dead_letter') then raise exception 'invalid_email_job_status' using errcode='22023'; end if;
  if p_limit not between 1 and 200 then raise exception 'invalid_limit' using errcode='22023'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('id',j.id,'kind',j.kind,'aggregateId',j.aggregate_id,'status',j.status,'attempts',j.attempts,'availableAt',j.available_at,'providerMessageId',j.provider_message_id,'lastError',j.last_error,'createdAt',j.created_at,'sentAt',j.sent_at) order by j.created_at desc,j.id desc),'[]'::jsonb)
  into result from (select * from private.transactional_email_jobs where normalized is null or status=normalized order by created_at desc,id desc limit p_limit) j;
  return jsonb_build_object('ok',true,'items',result);
end;
$function$;

create or replace function public.super_admin_retry_transactional_email_job_v1(p_job_id bigint)
returns boolean
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if auth.uid() is null or not coalesce(private.is_super_admin(),false) then raise exception 'super_admin_required' using errcode='42501'; end if;
  update private.transactional_email_jobs
  set status='pending',attempts=0,available_at=timezone('utc',now()),locked_at=null,locked_by=null,last_error=null
  where id=p_job_id and status in ('failed','dead_letter');
  return found;
end;
$function$;

