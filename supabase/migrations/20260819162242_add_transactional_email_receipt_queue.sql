create table if not exists private.transactional_email_jobs (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('order_payment_receipt','event_payment_receipt')),
  aggregate_id uuid not null,
  user_id uuid not null,
  payload jsonb not null check (jsonb_typeof(payload)='object'),
  status text not null default 'pending' check (status in ('pending','processing','failed','sent','dead_letter')),
  attempts integer not null default 0 check (attempts between 0 and 100),
  available_at timestamptz not null default timezone('utc',now()),
  locked_at timestamptz,
  locked_by text,
  provider_message_id text,
  last_error text,
  created_at timestamptz not null default timezone('utc',now()),
  sent_at timestamptz,
  unique(kind,aggregate_id)
);

alter table private.transactional_email_jobs enable row level security;
revoke all on table private.transactional_email_jobs from public,anon,authenticated;
revoke all on sequence private.transactional_email_jobs_id_seq from public,anon,authenticated;
create index if not exists transactional_email_jobs_queue_idx on private.transactional_email_jobs(available_at,id) where status in ('pending','failed','processing');
create index if not exists transactional_email_jobs_user_idx on private.transactional_email_jobs(user_id,created_at desc);

create or replace function private.build_order_payment_receipt_payload_v1(p_order_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $function$
declare
  o public.orders%rowtype;
  recipient_email text;
  recipient_name text;
  recipient_locale text;
  payment_provider text;
  payment_method text;
  paid_at timestamptz;
  items jsonb;
begin
  select * into o from public.orders where id=p_order_id;
  if o.id is null then raise exception 'order_not_found' using errcode='P0002'; end if;
  if o.payment_status<>'paid' then raise exception 'order_not_paid' using errcode='55000'; end if;

  select lower(btrim(coalesce(u.email,''))),nullif(btrim(coalesce(p.display_name,'')),''),coalesce(nullif(btrim(p.locale),''),'tr')
  into recipient_email,recipient_name,recipient_locale
  from auth.users u left join public.profiles p on p.id=u.id
  where u.id=o.user_id;

  select pr.provider,pr.payment_method_type,coalesce(pr.captured_at,pr.updated_at)
  into payment_provider,payment_method,paid_at
  from public.payment_records pr
  where pr.order_id=o.id and pr.status='captured'
  order by pr.captured_at desc nulls last,pr.updated_at desc
  limit 1;

  select coalesce(jsonb_agg(jsonb_build_object(
    'name',oi.product_name,
    'variant',nullif(btrim(coalesce(oi.variant_name,'')),''),
    'quantity',oi.quantity,
    'lineTotalMinor',oi.line_total_minor
  ) order by oi.created_at,oi.id),'[]'::jsonb)
  into items
  from public.order_items oi where oi.order_id=o.id;

  return jsonb_build_object(
    'schemaVersion',1,
    'documentKind','payment_receipt',
    'legalInvoice',false,
    'recipientEmail',recipient_email,
    'recipientName',recipient_name,
    'locale',recipient_locale,
    'orderId',o.id,
    'orderNumber',o.order_number,
    'currency',o.currency,
    'subtotalMinor',o.subtotal_minor,
    'discountMinor',o.discount_minor,
    'taxMinor',o.tax_minor,
    'shippingMinor',o.shipping_minor,
    'totalMinor',o.total_minor,
    'placedAt',o.placed_at,
    'paidAt',paid_at,
    'paymentProvider',payment_provider,
    'paymentMethod',payment_method,
    'items',items
  );
end;
$function$;

create or replace function private.build_event_payment_receipt_payload_v1(p_reservation_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $function$
declare
  f private.event_reservation_finance%rowtype;
  r public.event_reservations%rowtype;
  event_title text;
  recipient_email text;
  recipient_name text;
  recipient_locale text;
begin
  select * into f from private.event_reservation_finance where reservation_id=p_reservation_id;
  if f.reservation_id is null then raise exception 'event_finance_not_found' using errcode='P0002'; end if;
  if f.payment_status<>'paid' then raise exception 'event_payment_not_paid' using errcode='55000'; end if;
  select * into r from public.event_reservations where id=p_reservation_id;
  if r.id is null then raise exception 'event_reservation_not_found' using errcode='P0002'; end if;
  select e.title into event_title from public.events e where e.id=r.event_id;
  select lower(btrim(coalesce(u.email,''))),coalesce(nullif(btrim(coalesce(p.display_name,'')),''),nullif(btrim(coalesce(r.guest_name,'')),'')),coalesce(nullif(btrim(p.locale),''),'tr')
  into recipient_email,recipient_name,recipient_locale
  from auth.users u left join public.profiles p on p.id=u.id
  where u.id=f.user_id;

  return jsonb_build_object(
    'schemaVersion',1,
    'documentKind','event_payment_receipt',
    'legalInvoice',false,
    'recipientEmail',recipient_email,
    'recipientName',recipient_name,
    'locale',recipient_locale,
    'reservationId',r.id,
    'reservationCode',r.reservation_code,
    'eventId',r.event_id,
    'eventTitle',event_title,
    'guestCount',f.guest_count,
    'ticketPriceMinor',f.ticket_price_minor,
    'totalMinor',f.total_minor,
    'currency',f.currency,
    'paidAt',f.paid_at,
    'paymentProvider',f.provider
  );
end;
$function$;

create or replace function private.enqueue_order_payment_receipt_email_v1()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if new.payment_status='paid' and (tg_op='INSERT' or old.payment_status is distinct from new.payment_status) then
    insert into private.transactional_email_jobs(kind,aggregate_id,user_id,payload)
    values('order_payment_receipt',new.id,new.user_id,private.build_order_payment_receipt_payload_v1(new.id))
    on conflict(kind,aggregate_id) do nothing;
  end if;
  return new;
end;
$function$;

