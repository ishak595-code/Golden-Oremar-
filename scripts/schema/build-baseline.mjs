// Writes supabase/schema/baseline.sql from a live catalogue export.
//
//   node scripts/schema/build-baseline.mjs <catalog.json>
//
// The export comes from scripts/schema/export-catalog.sql run against the live
// project (Supabase SQL editor or the MCP execute_sql tool; any read-only
// connection works). The baseline recreates the application schemas
// (public, private, api_internal, api_public_bridge) exactly: tables, columns,
// defaults, constraints, indexes, sequences, views, every function, triggers,
// row level security, policies, privileges, default privileges and the app's
// event trigger. It holds no rows.
//
// Order follows what Postgres needs on an empty database: tables without
// defaults first, then functions (with function body checks off, as pg_dump
// does), then defaults, constraints, indexes, views, triggers, policies and
// privileges. compare-catalog.mjs proves the result equals the live schema.

import fs from 'node:fs';

const input = process.argv[2];
if (!input) { console.error('Usage: node scripts/schema/build-baseline.mjs <catalog.json>'); process.exit(1); }
const cat = JSON.parse(fs.readFileSync(input, 'utf8'));
const APP = ['public', 'private', 'api_internal', 'api_public_bridge'];
const ROLES = ['anon', 'authenticated', 'service_role'];
const OWNERS = new Set(['postgres', 'supabase_admin', 'pg_database_owner']);
const out = [];
const emit = (...lines) => out.push(...lines);
const q = name => /^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name) ? name : `"${name.replace(/"/g, '""')}"`;
const RESERVED = new Set(['user', 'order', 'group', 'default', 'check', 'table', 'column', 'from', 'to', 'select', 'where', 'end', 'limit', 'offset', 'primary', 'references', 'constraint', 'unique', 'all', 'and', 'or', 'not', 'null', 'true', 'false', 'role', 'position']);
const rel = (schema, name) => `${q(schema)}.${q(name)}`;
const lit = text => `'${String(text).replace(/'/g, "''")}'`;
const grantee = name => name === 'PUBLIC' ? 'PUBLIC' : q(name);

function privileges(acl, skip = OWNERS) {
  const byGrantee = new Map();
  for (const entry of acl || []) {
    if (skip.has(entry.grantee)) continue;
    if (!byGrantee.has(entry.grantee)) byGrantee.set(entry.grantee, []);
    byGrantee.get(entry.grantee).push(entry.priv);
  }
  return byGrantee;
}

emit(
  '-- Golden Oremar application schema baseline.',
  `-- Generated by scripts/schema/build-baseline.mjs from the live catalogue (${cat.exportedAt || 'export date in commit'}).`,
  '-- Recreates public, private, api_internal and api_public_bridge exactly; no rows.',
  '-- Needs what a Supabase project already has: auth, storage, vault, cron, net,',
  '-- the extensions schema (pgcrypto, pg_trgm, uuid-ossp) and the API roles.',
  '-- Do not edit by hand: regenerate, then prove it with compare-catalog.mjs.',
  '',
  'set check_function_bodies = off;',
  'set client_min_messages = warning;',
  'set search_path = "$user", public, extensions;',
  '',
);

// 1. Schemas.
emit('-- Schemas');
for (const schema of [...cat.schemas].sort((a, b) => APP.indexOf(a.name) - APP.indexOf(b.name))) {
  emit(`create schema if not exists ${q(schema.name)};`);
  if (schema.comment) emit(`comment on schema ${q(schema.name)} is ${lit(schema.comment)};`);
}
emit('');

// 2. Sequences that are not identity columns.
emit('-- Sequences');
for (const seq of cat.sequences || []) {
  if (seq.owned?.identity) continue;
  const max = seq.type === 'bigint' && seq.max >= 9.2e18 ? '' : ` maxvalue ${seq.max}`;
  emit(`create sequence if not exists ${rel(seq.schema, seq.name)} as ${seq.type} increment by ${seq.inc} minvalue ${seq.min}${max} start with ${seq.start} cache ${seq.cache}${seq.cycle ? ' cycle' : ''};`);
}
emit('');

// 3. Tables: columns only. Defaults and constraints come after the functions.
emit('-- Tables');
const tables = [...cat.tables].sort((a, b) => APP.indexOf(a.schema) - APP.indexOf(b.schema) || a.name.localeCompare(b.name));
for (const t of tables) {
  const cols = t.columns.map(c => {
    let line = `  ${q(c.name)} ${c.type}`;
    if (c.collation) line += ` collate "${c.collation}"`;
    if (c.identity === 'a') line += ' generated always as identity';
    else if (c.identity === 'd') line += ' generated by default as identity';
    else if (c.generated === 's') line += ` generated always as (${c.default}) stored`;
    if (c.notnull) line += ' not null';
    return line;
  });
  emit(`create table ${rel(t.schema, t.name)} (`, cols.join(',\n'), ');');
}
emit('');

// 4. Functions, bodies unchecked until everything they read exists.
emit('-- Functions');
const functions = [...cat.functions].sort((a, b) => a.sig.localeCompare(b.sig));
for (const f of functions) emit(`${f.def.trim()};`, '');

// 5. Column defaults and sequence ownership.
emit('-- Column defaults');
for (const t of tables) for (const c of t.columns) {
  if (c.default != null && !c.identity && c.generated !== 's') emit(`alter table ${rel(t.schema, t.name)} alter column ${q(c.name)} set default ${c.default};`);
}
for (const seq of cat.sequences || []) {
  if (!seq.owned || seq.owned.identity) continue;
  const [schema, table] = seq.owned.table.split('.');
  emit(`alter sequence ${rel(seq.schema, seq.name)} owned by ${rel(schema, table)}.${q(seq.owned.col)};`);
}
emit('');

// 6. Constraints: keys and checks, then foreign keys once every key exists.
emit('-- Constraints');
for (const pass of [['p', 'u', 'x'], ['c'], ['f']]) {
  for (const t of tables) for (const k of t.constraints || []) {
    if (!pass.includes(k.type)) continue;
    emit(`alter table ${rel(t.schema, t.name)} add constraint ${q(k.name)} ${k.def};`);
  }
}
emit('');

// 7. Indexes that do not back a constraint.
emit('-- Indexes');
for (const t of tables) for (const index of t.indexes || []) emit(`${index};`);
emit('');

// 8. Views.
emit('-- Views');
for (const v of cat.views || []) {
  const options = v.options?.length ? ` with (${v.options.join(', ')})` : '';
  emit(`create ${v.kind === 'm' ? 'materialized view' : 'view'} ${rel(v.schema, v.name)}${options} as`, `${v.def.trim().replace(/;$/, '')};`);
}
emit('');

// 9. Triggers.
emit('-- Triggers');
for (const t of tables) for (const tg of t.triggers || []) {
  emit(`${tg.def};`);
  if (tg.enabled === 'D') emit(`alter table ${rel(t.schema, t.name)} disable trigger ${q(tg.name)};`);
}
emit('');

// 10. Row level security and policies.
emit('-- Row level security');
const CMD = { r: 'select', a: 'insert', w: 'update', d: 'delete', '*': 'all' };
for (const t of tables) {
  if (t.rls) emit(`alter table ${rel(t.schema, t.name)} enable row level security;`);
  if (t.force) emit(`alter table ${rel(t.schema, t.name)} force row level security;`);
  for (const p of t.policies || []) {
    const roles = (p.roles || ['public']).map(r => r === 'public' ? 'public' : q(r)).join(', ');
    let line = `create policy ${q(p.name)} on ${rel(t.schema, t.name)} as ${p.permissive ? 'permissive' : 'restrictive'} for ${CMD[p.cmd]} to ${roles}`;
    if (p.using) line += ` using (${p.using})`;
    if (p.check) line += ` with check (${p.check})`;
    emit(`${line};`);
  }
}
emit('');

// 11. Privileges: start from nothing for the API roles, then grant exactly.
emit('-- Privileges');
for (const schema of cat.schemas) {
  emit(`revoke all on schema ${q(schema.name)} from public, ${ROLES.join(', ')};`);
  for (const [who, privs] of privileges(schema.acl)) emit(`grant ${privs.join(', ').toLowerCase()} on schema ${q(schema.name)} to ${grantee(who)};`);
}
const tablePrivs = list => list.filter(p => p !== 'MAINTAIN');
for (const t of tables) {
  const name = rel(t.schema, t.name);
  emit(`revoke all on table ${name} from public, ${ROLES.join(', ')};`);
  for (const [who, privs] of privileges(t.acl)) {
    const kept = tablePrivs(privs);
    if (kept.length) emit(`grant ${kept.join(', ').toLowerCase()} on table ${name} to ${grantee(who)};`);
  }
  const columnGrants = new Map();
  for (const c of t.colacl || []) {
    if (OWNERS.has(c.grantee)) continue;
    const key = `${c.grantee}|${c.priv}`;
    if (!columnGrants.has(key)) columnGrants.set(key, []);
    columnGrants.get(key).push(q(c.col));
  }
  for (const [key, cols] of columnGrants) {
    const [who, priv] = key.split('|');
    emit(`grant ${priv.toLowerCase()} (${cols.join(', ')}) on table ${name} to ${grantee(who)};`);
  }
}
for (const v of cat.views || []) {
  const name = rel(v.schema, v.name);
  emit(`revoke all on table ${name} from public, ${ROLES.join(', ')};`);
  for (const [who, privs] of privileges(v.acl)) {
    const kept = tablePrivs(privs);
    if (kept.length) emit(`grant ${kept.join(', ').toLowerCase()} on table ${name} to ${grantee(who)};`);
  }
}
for (const seq of cat.sequences || []) {
  const name = rel(seq.schema, seq.name);
  emit(`revoke all on sequence ${name} from public, ${ROLES.join(', ')};`);
  for (const [who, privs] of privileges(seq.acl)) emit(`grant ${privs.join(', ').toLowerCase()} on sequence ${name} to ${grantee(who)};`);
}
for (const f of functions) {
  emit(`revoke all on function ${f.sig} from public, ${ROLES.join(', ')};`);
  for (const [who] of privileges(f.acl)) emit(`grant execute on function ${f.sig} to ${grantee(who)};`);
}
emit('');

// 12. Default privileges the migrations set for objects postgres creates.
emit('-- Default privileges');
const OBJ = { r: 'tables', S: 'sequences', f: 'functions' };
for (const d of cat.defacl || []) {
  if (d.role !== 'postgres' || !APP.includes(d.schema) || !OBJ[d.objtype]) continue;
  const scope = `alter default privileges for role postgres in schema ${q(d.schema)}`;
  emit(`${scope} revoke all on ${OBJ[d.objtype]} from public, ${ROLES.join(', ')};`);
  for (const [who, privs] of privileges(d.acl)) {
    const kept = d.objtype === 'r' ? tablePrivs(privs) : privs;
    if (kept.length) emit(`${scope} grant ${kept.join(', ').toLowerCase()} on ${OBJ[d.objtype]} to ${grantee(who)};`);
  }
}
emit('');

// 13. The app's own event trigger (Supabase's are created by the platform).
emit('-- Event triggers');
for (const e of cat.evt || []) {
  if (!APP.some(schema => e.fn.startsWith(`${schema}.`))) continue;
  const tags = e.tags?.length ? ` when tag in (${e.tags.map(lit).join(', ')})` : '';
  emit(`create event trigger ${q(e.name)} on ${e.event}${tags} execute function ${e.fn};`);
}
emit('');

// 14. Comments.
emit('-- Comments');
for (const t of tables) {
  if (t.comment) emit(`comment on table ${rel(t.schema, t.name)} is ${lit(t.comment)};`);
  for (const c of t.columns) if (c.comment) emit(`comment on column ${rel(t.schema, t.name)}.${q(c.name)} is ${lit(c.comment)};`);
}
for (const f of functions) if (f.comment) emit(`comment on function ${f.sig} is ${lit(f.comment)};`);

fs.mkdirSync('supabase/schema', { recursive: true });
fs.writeFileSync('supabase/schema/baseline.sql', out.join('\n') + '\n');
console.log(`Wrote supabase/schema/baseline.sql: ${tables.length} tables, ${functions.length} functions, ${(cat.views || []).length} views, ${(cat.sequences || []).length} sequences.`);
