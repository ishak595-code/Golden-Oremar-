// Imports representative product photos into the app.
//
// The images are generated outside this repository and arrive as short-lived
// download links in scripts/product-photos/sources.json ([{ slug, url }]).
// This runs in GitHub Actions (product-photos-import.yml), where those links
// are reachable: each image is downloaded, cropped to a square and written as
// WebP in two sizes (1200 px for the product page, 480 px for cards), the
// manifest the storefront reads is rebuilt, and the used links are cleared
// from sources.json so expired URLs do not linger in the history.
//
// A real photo uploaded in the admin panel always wins over these: the app
// uses a shipped photo only for a product that has no image of its own.
//
// An entry with "kind": "origin" is the product's second photo: where it
// comes from (the mountain region, the drying, the bez kese being filled).
// It goes to public/product-photos/origin and its own manifest, and the
// product page shows it as the second slide (see origin-prompts.json).

import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SOURCES = 'scripts/product-photos/sources.json';
const OUT = 'public/product-photos';
const MANIFEST = 'src/features/media/productPhotoManifest.ts';
const ORIGIN_OUT = 'public/product-photos/origin';
const ORIGIN_MANIFEST = 'src/features/media/productOriginPhotoManifest.ts';
const SLUG = /^[a-z0-9][a-z0-9-]{1,200}$/;

const sources = JSON.parse(fs.readFileSync(SOURCES, 'utf8'));
fs.mkdirSync(OUT, { recursive: true });
fs.mkdirSync(ORIGIN_OUT, { recursive: true });
let imported = 0;
const failures = [];
for (const entry of sources) {
  if (!entry?.url) continue;
  if (!SLUG.test(String(entry.slug || ''))) { failures.push(`unsafe slug ${entry.slug}`); continue; }
  try {
    const response = await fetch(entry.url, { signal: AbortSignal.timeout(60000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const input = Buffer.from(await response.arrayBuffer());
    const meta = await sharp(input).metadata();
    if (!meta.width || meta.width < 600) throw new Error(`too small (${meta.width}px)`);
    const dir = entry.kind === 'origin' ? ORIGIN_OUT : OUT;
    const square = sharp(input).rotate().resize(1200, 1200, { fit: 'cover', position: 'attention' });
    await square.clone().webp({ quality: 80, effort: 5 }).toFile(path.join(dir, `${entry.slug}.webp`));
    await square.clone().resize(480, 480).webp({ quality: 74, effort: 5 }).toFile(path.join(dir, `${entry.slug}-480.webp`));
    entry.url = '';
    entry.importedAt = new Date().toISOString().slice(0, 10);
    imported += 1;
  } catch (error) {
    failures.push(`${entry.slug}: ${error.message}`);
  }
}
const shipped = dir => fs.readdirSync(dir).filter(name => /^[a-z0-9-]+\.webp$/.test(name) && !name.endsWith('-480.webp')).map(name => name.slice(0, -5))
  .filter(slug => fs.existsSync(path.join(dir, `${slug}-480.webp`))).sort();
const slugs = shipped(OUT);
const originSlugs = shipped(ORIGIN_OUT);
fs.writeFileSync(ORIGIN_MANIFEST, `// Generated by scripts/product-photos/import.mjs. Second (origin) photos shipped\n// in public/product-photos/origin, shown as the second slide on the product page.\nexport const SHIPPED_ORIGIN_PHOTOS: readonly string[] = ${JSON.stringify(originSlugs, null, 1)};\n`);
fs.writeFileSync(MANIFEST, `// Generated by scripts/product-photos/import.mjs. Representative photos shipped\n// in public/product-photos; a real uploaded photo always takes precedence.\nexport const SHIPPED_PRODUCT_PHOTOS: readonly string[] = ${JSON.stringify(slugs, null, 1)};\n`);
fs.writeFileSync(SOURCES, `${JSON.stringify(sources, null, 1)}\n`);
console.log(`Imported ${imported} photo(s); ${slugs.length} product and ${originSlugs.length} origin photo(s) shipped in total.`);
if (failures.length) { console.error(failures.join('\n')); if (!imported) process.exit(1); }
