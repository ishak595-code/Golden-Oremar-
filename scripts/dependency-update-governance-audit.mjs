import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd();
const configPath=path.join(root,'.github','dependabot.yml');
const mobileQualityPath=path.join(root,'.github','workflows','mobile-quality.yml');
const swiftManifestPath=path.join(root,'ios','App','CapApp-SPM','Package.swift');

const fail=(message)=>{console.error(`Dependency update governance audit failed: ${message}`);process.exitCode=1;};
const read=(file)=>fs.readFileSync(file,'utf8');

for(const file of [configPath,mobileQualityPath,swiftManifestPath]){
  if(!fs.existsSync(file)) fail(`required governance file is missing: ${path.relative(root,file)}`);
}
if(process.exitCode) process.exit(process.exitCode);

const config=read(configPath);
const mobileQuality=read(mobileQualityPath);
const swiftManifest=read(swiftManifestPath);

if(!/^version:\s*2\s*$/m.test(config)) fail('Dependabot config must use version 2');
if(/open-pull-requests-limit:\s*0\b/.test(config)) fail('Dependabot version updates must not be disabled');
if(/version-update:semver-major/.test(config)) fail('major version updates must remain visible as individual reviewable PRs, not globally ignored');

const blocks=config.split(/\n(?=  - package-ecosystem:)/).filter((part)=>/package-ecosystem:/.test(part));
const expected=new Map([
  ['npm',{directory:'/',time:'04:00',groupMarkers:['production-minor-patch:','development-minor-patch:']}],
  ['github-actions',{directory:'/',time:'04:20',groupMarkers:['actions-minor-patch:']}],
  ['gradle',{directory:'/android',time:'04:40',groupMarkers:['android-minor-patch:']}]
]);
const seen=new Set();

for(const block of blocks){
  const ecosystem=block.match(/package-ecosystem:\s*["']?([^"'\s]+)["']?/)?.[1];
  if(!ecosystem){fail('could not parse a package-ecosystem block');continue;}
  if(!expected.has(ecosystem)){fail(`unexpected package ecosystem is independently managed: ${ecosystem}`);continue;}
  if(seen.has(ecosystem)){fail(`duplicate package ecosystem block: ${ecosystem}`);continue;}
  seen.add(ecosystem);
  const rule=expected.get(ecosystem);
  const directory=block.match(/\n\s+directory:\s*["']?([^"'\n]+)["']?\s*$/m)?.[1]?.trim();
  const time=block.match(/\n\s+time:\s*["']?([^"'\n]+)["']?\s*$/m)?.[1]?.trim();
  if(directory!==rule.directory) fail(`${ecosystem} must be managed from ${rule.directory}, got ${directory||'missing'}`);
  if(!/\n\s+interval:\s*["']?weekly["']?\s*$/m.test(block)) fail(`${ecosystem} must run weekly`);
  if(!/\n\s+day:\s*["']?monday["']?\s*$/m.test(block)) fail(`${ecosystem} must run on Monday`);
  if(time!==rule.time) fail(`${ecosystem} scheduled time drifted from ${rule.time} UTC`);
  if(!/\n\s+timezone:\s*["']?Etc\/UTC["']?\s*$/m.test(block)) fail(`${ecosystem} schedule must be timezone-pinned to Etc/UTC`);
  if(!/\n\s+open-pull-requests-limit:\s*8\s*$/m.test(block)) fail(`${ecosystem} open PR limit must remain 8`);
  if(!/\n\s+rebase-strategy:\s*["']?auto["']?\s*$/m.test(block)) fail(`${ecosystem} must automatically rebase stale update PRs`);
  for(const marker of rule.groupMarkers){
    if(!block.includes(marker)) fail(`${ecosystem} is missing update group ${marker}`);
  }
  if(!block.includes('- "minor"')||!block.includes('- "patch"')) fail(`${ecosystem} grouped updates must include minor and patch releases`);
}

for(const ecosystem of expected.keys()){
  if(!seen.has(ecosystem)) fail(`required package ecosystem is not dynamically monitored: ${ecosystem}`);
}
if(seen.size!==expected.size) fail(`expected exactly ${expected.size} managed ecosystems, found ${seen.size}`);

for(const match of config.matchAll(/target-branch:\s*["']?([^"'\s]+)["']?/g)){
  if(match[1]!=='main') fail(`Dependabot target branch must remain main, got ${match[1]}`);
}

if(/package-ecosystem:\s*["']?swift["']?/.test(config)) fail('Swift must not be independently updated because CapApp-SPM/Package.swift is generated by Capacitor CLI');
if(!swiftManifest.includes('DO NOT MODIFY THIS FILE - managed by Capacitor CLI commands')) fail('Swift dependency ownership marker is missing from generated CapApp-SPM manifest');

if(!/pull_request:\s*\n\s+branches:\s*\n\s+- main/m.test(mobileQuality)) fail('Mobile Quality Gate must continue to run on pull requests targeting main');
if(!mobileQuality.includes('npm audit --omit=dev --audit-level=low')) fail('Dependabot PRs must remain protected by the LOW-severity production advisory gate');

if(process.exitCode) process.exit(process.exitCode);
console.log('Dependency update governance audit passed: npm, GitHub Actions and Android Gradle are monitored weekly; generated Swift dependencies remain single-sourced through Capacitor; update PRs inherit the full main quality gate.');
