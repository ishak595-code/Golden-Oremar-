-- Schema DDL generator
--
-- Purpose: have the database emit its own CREATE TABLE / RLS / foreign key
-- DDL from the system catalogs, so schema snapshots are machine-generated
-- rather than hand-written. Used to close the table-level schema drift
-- documented in docs/SCHEMA_DRIFT_CLOSURE.md.
--
-- Why this exists: PostgreSQL provides pg_get_functiondef for functions and
-- pg_indexes.indexdef for indexes, but has no equivalent for tables. Writing
-- table DDL by hand is where mistakes hide - a missed IDENTITY clause, a
-- dropped NOT NULL, a forgotten check constraint. Generating it here keeps a
-- human (or an assistant) out of the authoring loop; the only remaining risk
-- is faithful copying, which an md5 comparison settles.
--
-- Usage: set the table list in `tl`, run, then write `sql_text` to a migration
-- file verbatim and confirm its md5 equals `live_md5`.
--
-- Design notes:
--   * identity and generated columns are emitted explicitly - omitting these
--     produces a table that looks right but rejects every insert
--   * NOT NULL is suppressed on identity columns because it is implied and
--     restating it is a syntax error
--   * RLS enable/force are emitted per table; skipping them would rebuild the
--     schema with row level security silently switched off
--   * foreign keys are separated out and emitted after all CREATE TABLE
--     statements, so the output can be replayed against an empty database in
--     any order without dependency failures
--
-- Not covered here, and deliberately so: column comments, storage parameters,
-- partitioning, table-level grants, triggers (handled separately), indexes
-- (use pg_indexes.indexdef, which is already canonical), and RLS policies
-- (use pg_policies). See docs/SCHEMA_DRIFT_CLOSURE.md for the full checklist.

with tl as (
  select c.oid as reloid, n.nspname, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where c.relkind = 'r'
    and (n.nspname || '.' || c.relname) in (
      -- replace this list with the tables you want to emit
      'private.submission_attempts'
    )
), cols as (
  select tl.reloid, string_agg(
    '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
    || case a.attidentity
         when 'a' then ' GENERATED ALWAYS AS IDENTITY'
         when 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
         else '' end
    || case when a.attgenerated = 's'
            then ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
            else '' end
    || case when a.attnotnull and a.attidentity = '' then ' NOT NULL' else '' end
    || case when a.attgenerated = '' and a.attidentity = '' and ad.adbin is not null
            then ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
            else '' end,
    E',\n' order by a.attnum) as coldef
  from tl
  join pg_attribute a on a.attrelid = tl.reloid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = tl.reloid and ad.adnum = a.attnum
  group by tl.reloid
), nonfk as (
  select tl.reloid, string_agg(
    '  CONSTRAINT ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid),
    E',\n' order by con.contype desc, con.conname) as condef
  from tl
  join pg_constraint con on con.conrelid = tl.reloid
  where con.contype <> 'f'
  group by tl.reloid
), tabstmt as (
  select tl.nspname, tl.relname,
    'CREATE TABLE IF NOT EXISTS ' || quote_ident(tl.nspname) || '.' || quote_ident(tl.relname)
    || E' (\n' || cols.coldef || coalesce(E',\n' || nonfk.condef, '') || E'\n);'
    || case when tl.relrowsecurity
            then E'\nALTER TABLE ' || quote_ident(tl.nspname) || '.' || quote_ident(tl.relname) || ' ENABLE ROW LEVEL SECURITY;'
            else '' end
    || case when tl.relforcerowsecurity
            then E'\nALTER TABLE ' || quote_ident(tl.nspname) || '.' || quote_ident(tl.relname) || ' FORCE ROW LEVEL SECURITY;'
            else '' end as stmt
  from tl
  join cols on cols.reloid = tl.reloid
  left join nonfk on nonfk.reloid = tl.reloid
), fkstmt as (
  select tl.nspname, tl.relname, con.conname,
    'ALTER TABLE ' || quote_ident(tl.nspname) || '.' || quote_ident(tl.relname)
    || ' ADD CONSTRAINT ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid) || ';' as stmt
  from tl
  join pg_constraint con on con.conrelid = tl.reloid
  where con.contype = 'f'
), combined as (
  select coalesce((select string_agg(stmt, E'\n\n' order by nspname, relname) from tabstmt), '')
      || coalesce(E'\n\n-- foreign keys (added after all tables exist)\n\n'
                  || (select string_agg(stmt, E'\n' order by nspname, relname, conname) from fkstmt), '') as full_sql
)
select full_sql as sql_text, md5(full_sql) as live_md5 from combined;
